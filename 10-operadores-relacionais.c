#include <stdio.h>

int main(void) {

    int a = 100, b = 101;

    printf("a < b  : %i\n", a < b);
    printf("a > b  : %i\n", a > b);
    printf("a <= b : %i\n", a <= b);
    printf("a >= b : %i\n", a >= b);
    printf("a == b : %i\n", a == b);
    printf("a != b : %i\n", a != b);

    return 0;
}
